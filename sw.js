// Personal Bug Book — service worker
// Caches the app shell for offline load; never caches Drive API calls.
// Also handles a best-effort daily reminder via Periodic Background Sync.

const CACHE_NAME = "bugbook-shell-v1";
const SHELL_FILES = [
  "./",
  "./index.html",
  "./manifest.json",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/icon-maskable-192.png",
  "./icons/icon-maskable-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_FILES)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  // Never intercept Drive/Google API calls or cross-origin requests — always go to network.
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});

// Best-effort daily nudge. Chrome controls actual timing based on site
// engagement — this is not a guaranteed alarm, see README/SETUP notes.
self.addEventListener("periodicsync", (event) => {
  if (event.tag === "bugbook-daily-reminder") {
    event.waitUntil(
      self.registration.showNotification("Personal Bug Book", {
        body: "Time to record today's observations.",
        icon: "icons/icon-192.png",
        badge: "icons/icon-192.png",
        tag: "bugbook-daily-reminder"
      })
    );
  }
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ("focus" in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow("./index.html");
    })
  );
});
